// `loft api`: the API reference, generated from the source each time it runs (src/cli/catalogue.ts), so it follows
// the library. Grouped by the public entry's layers (src/core.ts, shapes, motion, actions, checks, styles, in the order
// src/index.ts names them; the unproven modules last in their layer, labelled), then src/lib. Three prints:
//   full     every export: signature or fields, first sentence, cannot and relatives lists, an object's parts.
//            `loft api` prints it; docs/api.md is this text, committed.
//   one      `loft api <name>`: one entry with its whole comment.
//   compact  the form `loft context` ends with: a short sentence per value, specs' fields, limits kept.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { catalogue, cannotLines, firstSentence, relativesLines, exportsOf, type Entry, type Group, type Layer } from "./catalogue.ts";

const ROOT = resolve(import.meta.dir, "../..");
/** The public entry points: the library, and the plain functions `src/lib` adds (distance functions, folds, noise, raw WGSL). */
const ENTRIES = ["src/index.ts", "src/lib/index.ts"] as const;

export const GENERATED = "Generated by `bun src/cli/main.ts api` from the source; do not edit. Regenerate: `bun src/cli/main.ts api | tee docs/api.md`.";

/** The written orientation printed before the reference: the layers, the renderer, what a user can bring, the limits. */
export const preamble = (): string => readFileSync(resolve(ROOT, "src/cli/api_preamble.md"), "utf8").replace(/<!--[\s\S]*?-->\n*/g, "").trim();

/** Every group of every entry point; a declaration exported by both is shown once, under the first. */
function groups(): Group[] {
  const seen = new Set<string>();
  const out: Group[] = [];
  for (const entry of ENTRIES) for (const g of catalogue(entry)) {
    const keep = (e: Entry) => { const k = `${e.file}:${e.name}`; if (seen.has(k)) return false; seen.add(k); return true; };
    const values = g.values.filter(keep), types = g.types.filter(keep);
    if (values.length + types.length > 0) out.push({ ...g, values, types });
  }
  return out;
}

/** Layers in first-seen order, each with its groups. */
function byLayer(gs: readonly Group[]): { layer: Layer; groups: Group[] }[] {
  const out: { layer: Layer; groups: Group[] }[] = [];
  for (const g of gs) {
    let l = out.find((x) => x.layer.file === g.layer.file);
    if (!l) out.push((l = { layer: g.layer, groups: [] }));
    l.groups.push(g);
  }
  return out;
}

const layerTitle = (l: Layer) => (l.file === "src/lib/index.ts" ? "Library functions (import from src/lib/index.ts)" : `${l.name} (${l.file})`);
const groupTitle = (g: Group) => `${g.file}${g.unproven ? " (unproven: one user so far)" : ""}`;
const words = (s: string, n: number) => { const w = s.split(/\s+/); return w.length > n ? `${w.slice(0, n).join(" ")} ...` : s; };
const list = (label: string, items: readonly string[], indent: string) => (items.length === 0 ? [] : [`${indent}${label}:`, ...items.map((x) => `${indent}- ${x}`)]);

function fullEntry(e: Entry): string[] {
  const out = [`- **${e.name}**: ${e.doc === "" ? "(undocumented)" : firstSentence(e.doc)}`];
  if (e.signature !== "") out.push(`  \`${e.signature}\``);
  out.push(...list("cannot", cannotLines(e.doc), "  "), ...list("relatives", relativesLines(e.doc), "  "));
  for (const m of e.members) out.push(`  - \`${e.name}.${m.name}\`: ${m.doc === "" ? "(undocumented)" : firstSentence(m.doc)}`);
  return out;
}

/** The whole reference. */
export function apiFull(): string {
  const gs = groups();
  const out = ["# Loft API", "", GENERATED, "", preamble(), ""];
  for (const { layer, groups: here } of byLayer(gs)) {
    out.push(`## ${layerTitle(layer)}`, "", layer.line, "");
    for (const g of here) {
      out.push(`### ${groupTitle(g)}`, "", g.line === "" ? "(no opening comment)" : g.line, "");
      for (const e of g.values) out.push(...fullEntry(e));
      if (g.types.length > 0) {
        out.push("", "Types:");
        for (const t of g.types) out.push(`- **${t.name}**: ${t.doc === "" ? "" : `${firstSentence(t.doc)} `}\`${t.signature}\``);
      }
      out.push("");
    }
  }
  const values = gs.flatMap((g) => g.values), types = gs.flatMap((g) => g.types);
  const bare = gs.flatMap((g) => g.values.filter((e) => e.doc === "").map((e) => `${e.name} (${g.file})`));
  const noLimits = gs.filter((g) => /Shapes|Motion/.test(g.layer.name)).flatMap((g) => g.values.filter((e) => /^(function|const)/.test(e.signature) && cannotLines(e.doc).length === 0).map((e) => e.name));
  out.push("## Coverage", "", `${values.length + types.length} exports (${values.length} values, ${types.length} types) from ${ENTRIES.join(" and ")}.`, "",
    `Values with no doc comment (${bare.length}): ${bare.join(", ")}.`, "",
    `Shape and motion functions whose comment states no limits (${noLimits.length}): ${noLimits.join(", ")}.`, "");
  return out.join("\n");
}

export class ApiError extends Error {}

/** One name, with everything its comment says. */
export function apiOne(name: string): string {
  const hits = ENTRIES.flatMap((entry) => { const e = exportsOf(resolve(ROOT, entry)).get(name); return e ? [e] : []; })
    .filter((e, i, a) => a.findIndex((x) => x.file === e.file) === i);
  if (hits.length === 0) {
    const all = ENTRIES.flatMap((entry) => [...exportsOf(resolve(ROOT, entry)).keys()]);
    const near = all.filter((k) => k.toLowerCase().includes(name.toLowerCase())).slice(0, 12);
    throw new ApiError(`no export named "${name}"${near.length > 0 ? ` (names containing it: ${near.join(", ")})` : ""}`);
  }
  return hits.map((e) => [
    `${e.name}  (${e.kind}, ${e.file})`, "", e.signature, "", e.doc === "" ? "(no doc comment)" : e.doc,
    ...e.members.flatMap((m) => ["", `${e.name}.${m.name}: ${m.doc === "" ? "(undocumented)" : m.doc}`]),
  ].join("\n")).join("\n\n");
}

/**
 * Modules whose names say what they do (arithmetic, distance functions, the compiler's entry points) print by name only
 * in the compact form; that, and a sentence cut at twelve words, is what keeps `loft context` readable whole.
 */
const NAMES_ONLY = (g: Group) => g.layer.file === "src/lib/index.ts" || /^src\/(expr|artefact)\.ts$|^src\/compile\//.test(g.file);

/** The short form for `loft context`. */
export function apiCompact(): string {
  const out = ["# The API (compact: `loft api` prints it all, `loft api <name>` one entry whole)", "", preamble(), ""];
  for (const { layer, groups: here } of byLayer(groups())) {
    out.push(`## ${layerTitle(layer)}`, "");
    for (const g of here) {
      out.push(`### ${groupTitle(g)}${g.line === "" ? "" : `: ${words(g.line, 10)}`}`);
      const terse = NAMES_ONLY(g);
      for (const e of g.values.filter((x) => x.doc !== "" && !terse)) {
        out.push(`- ${e.name}: ${words(firstSentence(e.doc), 10)}`);
        out.push(...list("cannot", cannotLines(e.doc).map((x) => words(x, 18)), "  "), ...list("relatives", relativesLines(e.doc).map((x) => words(x, 18)), "  "));
        if (e.members.length > 0) out.push(`  parts: ${e.members.map((m) => m.name).join(", ")}`);
      }
      const bare = g.values.filter((x) => x.doc === "" || terse);
      if (bare.length > 0) out.push(`- ${terse ? "values" : "also (no comment)"}: ${bare.map((x) => (x.members.length > 0 ? `${x.name} {${x.members.map((m) => m.name).join(", ")}}` : x.name)).join(", ")}`);
      // A spec's fields are what a caller writes, so they are kept; other types by name.
      const isSpec = (t: Entry) => /(Spec|Options)$/.test(t.name) && t.signature.includes("{");
      for (const t of g.types.filter(isSpec)) out.push(`- ${t.name} ${t.signature.slice(t.signature.indexOf("{"))}`);
      const rest = g.types.filter((t) => !isSpec(t));
      if (rest.length > 0) out.push(`- types: ${rest.map((t) => t.name).join(", ")}`);
      out.push("");
    }
  }
  return out.join("\n");
}
